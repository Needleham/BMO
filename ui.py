class Spinner:
  FRAMES = ["|", "/", "-", "\\"]
  PHRASES = [
    "beep boop...",
    "I am a little living boy",
    "Who wants to play video games?",
    "Be more",
    "Calculating",
    "hmmmmmmm",
    "blooooooo",
    "I am BMO",
    "Does this unit have a soul?",
    "Scanning..."
  ]

  def __init__(self):
    self.message = random.choice(self.PHRASES)
    self._stop_event = threading.Event()
    self._thread = threading.Thread(target=self._spin, daemon=True)
    
  def _spin(self):
    i = 0
    printed = False
    while not self._stop_event.is_set():
      frame = self.FRAMES[i % len(self.FRAMES)]
      if printed:
        sys.stdout.write("\033[1A")
      sys.stdout.write(f"\r\033[2K {frame} {self.message}\n")
      sys.stdout.flush()
      printed = True
      time.sleep(0.1)
      i += 1

  def start(self):
    self._thread.start()

  def stop(self):
    self._stop_event.set()
    self._thread.join()
    sys.stdout.write("\033[1A\r\033[2K")
    sys.stdout.flush()

